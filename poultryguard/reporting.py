"""Automatic veterinary case-report generation.

Implements PDF requirement #6 (auto-compile a case file for the vet) and mirrors
the exact record fields shown in the PDF example (chick ref, age, detection
time, zone, status, body posture, head/legs/wings, recent movement).
"""
from __future__ import annotations
import json
from datetime import datetime


def _loads(x):
    if isinstance(x, (dict, list)):
        return x
    try:
        return json.loads(x) if x else {}
    except Exception:
        return {}


def build_case_report(case: dict, actions: list[dict] | None = None,
                      farm=None, house=None) -> str:
    """Return a Markdown case report ready to send to the veterinarian."""
    prof = _loads(case.get("posture_profile"))
    pm = _loads(case.get("premortality"))
    actions = actions or []
    created = datetime.fromtimestamp(case.get("created_at", 0)).strftime("%Y-%m-%d %H:%M:%S")

    lines = []
    lines.append(f"# Poultry Mortality Case Report — Case #{case.get('id')}")
    lines.append("")
    lines.append(f"- **Farm / House:** {case.get('farm_id','?')} / {case.get('house_id','?')}")
    lines.append(f"- **Chick reference:** {case.get('chick_ref','?')}")
    lines.append(f"- **Flock age:** {case.get('age_days','?')} days")
    lines.append(f"- **Detection time:** {case.get('detected_time','?')}  (logged {created})")
    lines.append(f"- **Location:** Zone {case.get('zone','?')}")
    lines.append(f"- **Status:** {case.get('status','open')}")
    lines.append(f"- **AI mortality score:** {case.get('score','?')}  "
                 f"(immobile {case.get('immobile_s',0):.0f}s, isolation {case.get('isolation',0):.2f})")
    lines.append(f"- **Trigger:** {case.get('reason','')}")
    lines.append("")
    lines.append("## Body posture profile")
    lines.append(f"- Posture class: **{case.get('posture','unknown')}**")
    if prof:
        for k in ("body", "head", "neck", "legs", "wings"):
            if k in prof:
                lines.append(f"- {k.capitalize()}: {prof[k]}")
    lines.append("")
    if pm:
        lines.append("## Pre-mortality behaviour (recent window)")
        lines.append("| t-minus (s) | speed (px/s) |")
        lines.append("|---|---|")
        for row in pm[:12]:
            lines.append(f"| {row.get('t_minus_s')} | {row.get('speed_px_s')} |")
        lines.append("")
    if case.get("snapshot_path"):
        lines.append(f"## Evidence\n- Snapshot: `{case['snapshot_path']}`")
        lines.append("")
    if actions:
        lines.append("## Veterinary actions")
        for a in actions:
            ts = datetime.fromtimestamp(a.get("created_at", 0)).strftime("%H:%M:%S")
            lines.append(f"- [{ts}] **{a.get('action')}** — {a.get('detail','')}"
                         + (f" ({a.get('vet_name')})" if a.get("vet_name") else ""))
        lines.append("")
    lines.append("---")
    lines.append("*Generated by PoultryGuard AI. This is an early-warning / "
                 "decision-support output; the attending veterinarian makes the "
                 "final diagnosis and treatment decision.*")
    return "\n".join(lines)
